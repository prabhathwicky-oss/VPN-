#!/usr/bin/env python3
"""
Applies YPN's Android settings on top of the project generated by
`flutter create` (so the android/ folder always matches the CI Flutter version).

Env vars:
  ADMOB_APP_ID   AdMob application id (defaults to Google's test app id)
  APP_NAME       launcher label
"""
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ANDROID = os.path.join(ROOT, "android")
APP = os.path.join(ANDROID, "app")
OVR = os.path.join(ROOT, "android_overrides")

ADMOB_APP_ID = os.environ.get("ADMOB_APP_ID") or "ca-app-pub-3940256099942544~3347511713"
APP_NAME = os.environ.get("APP_NAME") or "YPN VPN"
APP_ID = os.environ.get("ANDROID_PACKAGE") or "com.ypnvpn.app"


def die(msg):
    print("patch_android: " + msg, file=sys.stderr)
    sys.exit(1)


def patch_gradle():
    kts = os.path.join(APP, "build.gradle.kts")
    groovy = os.path.join(APP, "build.gradle")
    if os.path.exists(kts):
        s = open(kts).read()
        # applicationId can differ from the Kotlin namespace generated by flutter create
        s = re.sub(r'applicationId\s*=\s*"[^"]*"', 'applicationId = "%s"' % APP_ID, s, count=1)
        s, n = re.subn(r"minSdk\s*=\s*flutter\.minSdkVersion", "minSdk = 24", s)
        if n == 0 and "minSdk = 24" not in s:
            s = re.sub(r"(defaultConfig\s*\{)", r"\1\n        minSdk = 24", s, count=1)
        if "abiFilters" not in s:
            s = re.sub(r"(defaultConfig\s*\{)",
                       r'\1\n        ndk { abiFilters += listOf("armeabi-v7a", "arm64-v8a", "x86_64") }', s, count=1)
        if 'create("release")' not in s:
            block = '''
    signingConfigs {
        create("release") {
            val ks = System.getenv("ANDROID_KEYSTORE_PATH")
            if (ks != null && file(ks).exists()) {
                storeFile = file(ks)
                storePassword = System.getenv("ANDROID_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("ANDROID_KEY_ALIAS")
                keyPassword = System.getenv("ANDROID_KEY_PASSWORD")
            }
        }
    }

    packaging {
        jniLibs { useLegacyPackaging = true }
    }

    buildTypes {'''
            s, n = re.subn(r"\n\s*buildTypes\s*\{", block, s, count=1)
            if n == 0:
                die("could not find buildTypes in build.gradle.kts")
        s = re.sub(
            r'signingConfig\s*=\s*signingConfigs\.getByName\("debug"\)',
            'signingConfig = if (System.getenv("ANDROID_KEYSTORE_PATH") != null) '
            'signingConfigs.getByName("release") else signingConfigs.getByName("debug")\n'
            '            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")',
            s, count=1)
        open(kts, "w").write(s)
    elif os.path.exists(groovy):
        s = open(groovy).read()
        s = re.sub(r'applicationId\s+"[^"]*"', 'applicationId "%s"' % APP_ID, s, count=1)
        s = re.sub(r"minSdkVersion\s+flutter\.minSdkVersion", "minSdkVersion 24", s)
        s = re.sub(r"minSdk\s*=\s*flutter\.minSdkVersion", "minSdk = 24", s)
        if "useLegacyPackaging" not in s:
            s = re.sub(r"(android\s*\{)", r"\1\n    packagingOptions { jniLibs { useLegacyPackaging true } }", s, count=1)
        open(groovy, "w").write(s)
    else:
        die("no app/build.gradle(.kts) — did flutter create run?")


def patch_manifest():
    path = os.path.join(APP, "src", "main", "AndroidManifest.xml")
    s = open(path).read()
    perms = [
        "android.permission.INTERNET",
        "android.permission.ACCESS_NETWORK_STATE",
        "android.permission.FOREGROUND_SERVICE",
        "android.permission.POST_NOTIFICATIONS",
    ]
    for p in perms:
        if p not in s:
            s = s.replace("<application", '<uses-permission android:name="%s" />\n    <application' % p, 1)
    s = re.sub(r'android:label="[^"]*"', 'android:label="%s"' % APP_NAME, s, count=1)
    if "com.google.android.gms.ads.APPLICATION_ID" not in s:
        meta = ('\n        <meta-data android:name="com.google.android.gms.ads.APPLICATION_ID" '
                'android:value="%s"/>' % ADMOB_APP_ID)
        s = re.sub(r"(<application[^>]*>)", r"\1" + meta, s, count=1)
    open(path, "w").write(s)


def copy_overrides():
    res_src = os.path.join(OVR, "res")
    res_dst = os.path.join(APP, "src", "main", "res")
    if os.path.isdir(res_src):
        for root, _dirs, files in os.walk(res_src):
            rel = os.path.relpath(root, res_src)
            os.makedirs(os.path.join(res_dst, rel), exist_ok=True)
            for f in files:
                shutil.copy2(os.path.join(root, f), os.path.join(res_dst, rel, f))
    shutil.copy2(os.path.join(OVR, "proguard-rules.pro"), os.path.join(APP, "proguard-rules.pro"))


def patch_gradle_properties():
    path = os.path.join(ANDROID, "gradle.properties")
    s = open(path).read() if os.path.exists(path) else ""
    if "org.gradle.jvmargs" not in s:
        s += "\norg.gradle.jvmargs=-Xmx4g\n"
    open(path, "w").write(s)


if __name__ == "__main__":
    patch_gradle()
    patch_manifest()
    copy_overrides()
    patch_gradle_properties()
    print("patch_android: OK (AdMob app id %s)" % ("TEST" if "3940256099942544" in ADMOB_APP_ID else "custom"))
